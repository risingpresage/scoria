#!/usr/bin/env python3
"""Regenerate `crates/gguf/src/iq_tables.rs` from llama.cpp's `ggml-common.h`.

The IQ quantisers need ggml's grids and sign tables verbatim; transcribing a few
thousand constants by hand is not a correctness strategy. Run this against the
header from the llama.cpp commit you are targeting:

    curl -sL https://raw.githubusercontent.com/ggml-org/llama.cpp/master/ggml/src/ggml-common.h \
        -o /tmp/ggml-common.h
    python3 scripts/gen-iq-tables.py /tmp/ggml-common.h

The emitted file carries an FNV-1a digest of every value; `dequant::tests::
iq_tables_are_unchanged_from_ggml` recomputes it, so editing a table by hand fails
the suite. Keep the `#[cfg(test)]` on the digest constant: it is test-only.
"""
import pathlib
import re
import sys

FNV_OFFSET, FNV_PRIME = 0xCBF29CE484222325, 0x100000001B3

TABLES = [
    ("kmask_iq2xs", "KMASK_IQ2XS", "u8", 8),
    ("ksigns_iq2xs", "KSIGNS_IQ2XS", "u8", 128),
    ("iq2xs_grid", "IQ2XS_GRID", "u64", 512),
    ("iq2s_grid", "IQ2S_GRID", "u64", 1024),
    ("iq3xxs_grid", "IQ3XXS_GRID", "u32", 256),
    ("iq3s_grid", "IQ3S_GRID", "u32", 512),
]


def main() -> int:
    src = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "/tmp/ggml-common.h").read_text()
    digest = FNV_OFFSET
    out = [
        "// @generated by scripts/gen-iq-tables.py from ggml-common.h. Do not edit by hand.",
        "//",
        "// ggml's IQ quantisation grids and sign tables, copied verbatim so the dequantisers in",
        "// `dequant.rs` match the reference. Regenerate with scripts/gen-iq-tables.py; the",
        "// digest below is recomputed by a test, so a hand edit fails the suite.",
        "",
    ]
    for c_name, r_name, ty, size in TABLES:
        m = re.search(
            rf"GGML_TABLE_BEGIN\((\w+), {c_name}, ([^)]+)\)\s*\n(.*?)GGML_TABLE_END", src, re.S
        )
        if not m:
            raise SystemExit(f"table {c_name} not found")
        vals = [
            int(re.sub(r"[uUlL]+$", "", tok), 0)
            for tok in re.findall(r"0x[0-9a-fA-F]+[uUlL]*|-?\d+[uUlL]*", m.group(3))
        ]
        if len(vals) != size:
            raise SystemExit(f"{c_name}: {len(vals)} values, expected {size}")
        for v in vals:
            for b in v.to_bytes(8, "little"):
                digest = ((digest ^ b) * FNV_PRIME) & 0xFFFFFFFFFFFFFFFF
        out.append(f"pub static {r_name}: [{ty}; {size}] = [")
        for i in range(0, size, 8):
            out.append("    " + ", ".join(hex(v) for v in vals[i : i + 8]) + ",")
        out.append("];")
        out.append("")
    out += [
        "/// FNV-1a over every table value, little-endian u64. Only the table-integrity test",
        "/// reads it, so it does not exist in a release build.",
        "#[cfg(test)]",
        f"pub const GGML_TABLE_DIGEST: u64 = 0x{digest:016x};",
    ]
    pathlib.Path("crates/gguf/src/iq_tables.rs").write_text("\n".join(out) + "\n")
    print(f"wrote crates/gguf/src/iq_tables.rs (digest 0x{digest:016x})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
